"""Storage-neutral repository contracts shared by persistence adapters."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Generic, Protocol, TypeVar, runtime_checkable, TYPE_CHECKING

from app.domain.plan import Plan, PlanStatus
from app.domain.prompt import AgentName, AgentPrompt
from app.domain.scenario import Scenario
from app.domain.source import DataSource, DataSourceCreate, DataSourceUpdate
from app.domain.repository import (ExperimentPreparation, GroundedEntitySnapshot,
    RiskCandidateSnapshot, SignalRelationship, SimulationResultSnapshot)

T = TypeVar("T")

if TYPE_CHECKING:
    from app.integrations.contracts import (
        DeletionImpact, DuplicateDeletionPreview, DuplicateDeletionResult, Evidence,
        CanonicalSignal, EvidenceCreate, EvidenceKind, EvidenceProcessingAttempt,
        EvidenceUpdate, ExperimentPackage, FilterResult, GroundedEntity,
        InterpretationProposal,
    )


@dataclass(frozen=True, slots=True)
class Page(Generic[T]):
    """A stable page of results and an opaque backend continuation token."""

    items: tuple[T, ...]
    continuation_token: str | None = None


@runtime_checkable
class SourceRepository(Protocol):
    def create(self, values: DataSourceCreate) -> DataSource: ...
    def list(self, *, limit: int = 100, continuation_token: str | None = None) -> Page[DataSource]: ...
    def get(self, source_id: str) -> DataSource | None: ...
    def update(self, source_id: str, values: DataSourceUpdate) -> DataSource | None: ...
    def delete(self, source_id: str) -> bool: ...
    def due(self, now: datetime | None = None) -> list[DataSource]: ...
    def record_run(self, source_id: str, error: str | None = None) -> DataSource: ...
    def acquire_lease(self, source_id: str, owner: str, *, now: datetime,
                      expires_at: datetime) -> bool: ...
    def release_lease(self, source_id: str, owner: str) -> None: ...


@runtime_checkable
class EvidenceRepository(Protocol):
    """Persistence operations for evidence aggregates and deduplication."""

    def store(self, values: "EvidenceCreate") -> tuple["Evidence", bool]: ...
    def list(self, *, archived: bool | None = False, kind: "EvidenceKind | None" = None,
             include_duplicates: bool = False, limit: int = 50,
             continuation_token: str | None = None) -> "Page[Evidence]": ...
    def get(self, evidence_id: str) -> "Evidence | None": ...
    def has_signal(self, evidence_id: str) -> bool: ...
    def set_archived(self, evidence_id: str, archived: bool) -> "Evidence": ...
    def deletion_impact(self, evidence_id: str) -> "DeletionImpact": ...
    def duplicate_deletion_preview(self, evidence_id: str) -> "DuplicateDeletionPreview": ...
    def delete_unprotected_duplicates(self, evidence_id: str, *,
                                      delete_canonical: bool = False) -> "DuplicateDeletionResult": ...
    def remove_raw_content(self, evidence_id: str) -> "Evidence": ...
    def update(self, evidence_id: str, values: "EvidenceUpdate") -> "Evidence": ...
    def delete(self, evidence_id: str) -> None: ...


@runtime_checkable
class SignalRepository(Protocol):
    """Persistence operations for signals and immutable signal versions."""

    def attempts(self, evidence_id: str) -> tuple["EvidenceProcessingAttempt", ...]: ...
    def save_assessment(self, evidence_id: str, result: "FilterResult", context_version: str) -> None: ...
    def create_candidate(self, evidence: "Evidence", proposal: "InterpretationProposal",
                         context_version: str, retry_of_signal_id: str | None) -> str: ...
    def add_entity(self, version_id: str, item: "GroundedEntity") -> None: ...
    def add_effect(self, version_id: str, *, outcome: str, errors: list[str],
                   mapping_proposal: dict[str, object], local_validation: dict[str, object],
                   client_validation: dict[str, object], normalized_disruption: dict[str, object] | None,
                   catalog_version: str, schema_hash: str, context_version: str) -> None: ...
    def set_processing_state(self, version_id: str, state: str) -> None: ...
    def finalize(self, version_id: str, grounding_confidence: float,
                 mapping_confidence: float | None) -> "CanonicalSignal": ...
    def get_version(self, version_id: str) -> "CanonicalSignal": ...
    def list(self, *, review_status: str | None = None, limit: int = 50,
             continuation_token: str | None = None) -> "Page[CanonicalSignal]": ...
    def review(self, signal_id: str, decision: str, *,
               expected_version: int | None = None) -> "CanonicalSignal": ...
    def relate(self, source_version_id: str, target_version_id: str, *, relationship: str,
               confidence: float, rationale: str) -> dict[str, object]: ...


@runtime_checkable
class ExperimentRepository(Protocol):
    """Persistence operations for idempotent experiment handoff and results."""

    def prepare(self, version_ids: list[str]) -> ExperimentPreparation: ...
    def create_if_absent(self, package: "ExperimentPackage") -> "ExperimentPackage": ...
    def get(self, experiment_id: str) -> "ExperimentPackage | None": ...
    def mark_submitted(self, experiment_id: str, run_id: str, status: str) -> "ExperimentPackage": ...
    def save_result(self, experiment_id: str, result: SimulationResultSnapshot) -> None: ...
    def get_result(self, run_id: str) -> SimulationResultSnapshot | None: ...


@runtime_checkable
class PlanningCycleRepository(Protocol):
    """Persistence operations for versioned planning-cycle snapshots."""

    def save(self, cycle: "PlanningCycle", *, expected_version: int | None = None) -> "PlanningCycle": ...
    def get(self, cycle_id: str) -> "PlanningCycle | None": ...
    def list(self, *, limit: int = 100,
             continuation_token: str | None = None) -> "Page[PlanningCycle]": ...
    def relationships(self) -> list[SignalRelationship]: ...
    def risk_candidates(self, context_version: str) -> list[RiskCandidateSnapshot]: ...
    def grounded_entities(self, version_ids: list[str], entity_ids: set[str],
                          context_version: str) -> list[GroundedEntitySnapshot]: ...


@runtime_checkable
class PromptRepository(Protocol):
    """Persistence operations for the fixed set of agent prompt overrides."""

    def list(self, *, limit: int = 100,
             continuation_token: str | None = None) -> Page[AgentPrompt]: ...
    def get(self, agent: AgentName) -> AgentPrompt | None: ...
    def save(self, agent: AgentName, prompt: str) -> AgentPrompt: ...
    def reset(self, agent: AgentName) -> bool: ...


@runtime_checkable
class ScenarioRepository(Protocol):
    def save(self, scenario: Scenario) -> Scenario: ...
    def list(self, *, limit: int = 100, continuation_token: str | None = None) -> Page[Scenario]: ...
    def get(self, scenario_id: str) -> Scenario | None: ...


@runtime_checkable
class PlanRepository(Protocol):
    def save(self, plan: Plan) -> Plan: ...
    def list(self, *, limit: int = 100, continuation_token: str | None = None) -> Page[Plan]: ...
    def set_status(self, plan_id: str, status: PlanStatus) -> Plan | None: ...
